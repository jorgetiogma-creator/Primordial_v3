export async function translateChatMessageText(
  text: string,
  targetLang: AppLanguage
): Promise<{ translated: string; sourceLang?: string; fromFallback?: boolean }> {
  const clean = text.trim();
  if (!clean) return { translated: '' };

  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 5000);
  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${encodeURIComponent(
      targetLang
    )}&dt=t&q=${encodeURIComponent(clean)}`;
    const res = await fetch(url, { signal: controller.signal });
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data?.[0])) {
        const translated = data[0]
          .map((part: unknown) => (Array.isArray(part) && typeof part[0] === 'string' ? part[0] : ''))
          .join('')
          .trim();
        const sourceLang = typeof data?.[2] === 'string' ? data[2] : undefined;
        if (translated) {
          return { translated, sourceLang };
        }
      }
    }
  } catch {
    // Fallback to built-in phrase dictionary when offline or blocked
  } finally {
    window.clearTimeout(timeout);
  }

  const normalized = clean.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  const mapped = LOCAL_PHRASE_MAP[normalized]?.[targetLang];
  if (mapped) {
    return { translated: mapped, fromFallback: true };
  }
  const langOpt = getLanguageOption(targetLang);
  return { translated: `[${langOpt.nativeName}] ${clean}`, fromFallback: true };
}

