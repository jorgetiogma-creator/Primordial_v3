const DICTIONARIES: Record<AppLanguage, Record<TranslationKey, string>> = {
  es: ES_DICT,
  en: EN_DICT,
  pt: PT_DICT,
  fr: FR_DICT,
  de: DE_DICT,
  it: IT_DICT,
  ja: JA_DICT,
  ko: KO_DICT,
};

export function getLanguageOption(lang: AppLanguage): LanguageOption {
  return APP_LANGUAGES.find((l) => l.id === lang) || APP_LANGUAGES[0];
}

export function translateAppText(lang: AppLanguage, key: TranslationKey): string {
  return DICTIONARIES[lang]?.[key] || ES_DICT[key] || key;
}

interface I18nContextValue {
  language: AppLanguage;
  languageOption: LanguageOption;
  t: (key: TranslationKey) => string;
}

const I18nContext = createContext<I18nContextValue>({
  language: 'es',
  languageOption: APP_LANGUAGES[0],
  t: (key) => ES_DICT[key],
});

export const I18nProvider: React.FC<{
  language: AppLanguage;
  children: React.ReactNode;
}> = ({ language, children }) => {
  const safeLang: AppLanguage = DICTIONARIES[language] ? language : 'es';
  const value: I18nContextValue = {
    language: safeLang,
    languageOption: getLanguageOption(safeLang),
    t: (key) => translateAppText(safeLang, key),
  };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useTranslation(): I18nContextValue {
  return useContext(I18nContext);
}

